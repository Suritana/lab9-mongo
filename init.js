async function initDB() {
    try {
        await mongoose.connect(process.env.MONGO_URI);
        console.log('✓ Подключено к MongoDB');

        // Очистка коллекции
        const deleted = await Article.deleteMany({});
        console.log(`✓ Удалено старых статей: ${deleted.deletedCount}`);

        // Добавление новых статей
        const inserted = await Article.insertMany(articles);
        console.log(`✓ Добавлено статей: ${inserted.length}`);

        console.log('\nИнициализация базы данных завершена успешно!');
        process.exit(0);
    } catch (error) {
        console.error('Ошибка:', error.message);
        process.exit(1);
    }
}

